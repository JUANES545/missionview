namespace WindowScatter;

// Virtual-key protocol values, independent of how an input adapter captures them.
internal static class ModifierKeyCodes
{
    internal const int VK_SHIFT = 0x10, VK_CONTROL = 0x11, VK_MENU = 0x12;
    internal const int VK_LWIN = 0x5B, VK_RWIN = 0x5C;
    internal const int VK_LSHIFT = 0xA0, VK_RSHIFT = 0xA1, VK_LCONTROL = 0xA2, VK_RCONTROL = 0xA3;
    internal const int VK_LMENU = 0xA4, VK_RMENU = 0xA5;
}
